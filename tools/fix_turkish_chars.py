tr_pat = re.compile(r'[\u011f\u0130\u0131\u015f\u00e7\u00f6\u00fc\u011e\u015e\u00c7\u00d6\u00dc]')
for fpath in files:
    lines = [l for l in io.open(fpath, encoding='utf-8').read().split('\n') if l.strip()]
    q_total = 0; q_tr = 0
    for l in lines:
        o = json.loads(l)
        if o.get('type') == 'question':
            q_total += 1
            txt = o.get('question','') + ' '.join(o.get('choices',[])) + o.get('explanation','')
            if tr_pat.search(txt):
                q_tr += 1
    print(f"  {os.path.basename(fpath)}: {q_tr}/{q_total} soru Turkce karakterli")
