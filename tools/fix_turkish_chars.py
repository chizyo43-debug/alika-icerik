def restore_turkish(text):
    """Metindeki ASCII Turkce sozcukleri dogru karakterlere donusturur."""
    if not text:
        return text
    
    # Sozcuk bazli degistirme (buyuk-kucuk harf duyarliligi ile)
    def replace_word(match):
        word = match.group(0)
        lower = word.lower()
        if lower in SOZLUK:
            replacement = SOZLUK[lower]
            # Buyuk harf koruma
            if word[0].isupper():
                replacement = replacement[0].upper() + replacement[1:]
            if word.isupper():
                replacement = replacement.upper()
            return replacement
        return word
    
    # Sozcuk sinirlarini koruyarak degistir
    result = re.sub(r'[a-zA-Z\u00c0-\u024f]+', replace_word, text)
    return result

def process_file(fpath):
    lines = [l for l in io.open(fpath, encoding='utf-8').read().split('\n') if l.strip()]
    out = []
    changes = 0
    
    for line in lines:
        obj = json.loads(line)
        original = json.dumps(obj, ensure_ascii=False)
        
        # Tum metin alanlarini isle
        for field in ('question', 'explanation', 'title', 'body', 'topic'):
            if field in obj and isinstance(obj[field], str):
                obj[field] = restore_turkish(obj[field])
        
        for field in ('choices', 'hints', 'distractorWhy'):
            if field in obj and isinstance(obj[field], list):
                obj[field] = [restore_turkish(x) if isinstance(x, str) else x for x in obj[field]]
        
        new = json.dumps(obj, ensure_ascii=False)
        if new != original:
            changes += 1
        out.append(obj)
    
    with io.open(fpath, 'w', encoding='utf-8') as f:
        for obj in out:
            f.write(json.dumps(obj, ensure_ascii=False) + '\n')
    
    return changes

